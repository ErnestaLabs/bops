import "server-only";
import * as legacy from "./keychain-legacy";
import * as vault from "@/private-runtime/vault.mjs";
import { stateUser } from "./store";
const privateMode = () => process.env.BOPS_PRIVATE_RUNTIME === "1";
export const setSecret: typeof legacy.setSecret = (account, value) => privateMode() ? vault.setSecret(account, value) : legacy.setSecret(account, value);
export const getSecret: typeof legacy.getSecret = account => privateMode() ? vault.getSecret(account) : legacy.getSecret(account);
export const deleteSecret: typeof legacy.deleteSecret = account => privateMode() ? vault.deleteSecret(account) : legacy.deleteSecret(account);
const scoped = (name: string) => `${stateUser() || "private-owner"}:${name}`;
export const getUserSecret: typeof legacy.getUserSecret = name => privateMode() ? vault.getSecret(scoped(name)) : legacy.getUserSecret(name);
export const setUserSecret: typeof legacy.setUserSecret = (name, value) => privateMode() ? vault.setSecret(scoped(name), value) : legacy.setUserSecret(name, value);
export const deleteUserSecret: typeof legacy.deleteUserSecret = name => privateMode() ? vault.deleteSecret(scoped(name)) : legacy.deleteUserSecret(name);
